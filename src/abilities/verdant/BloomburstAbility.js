const TAU = Math.PI * 2;

/** Hard ceiling on flowers per cast. The editor's `flowers` slider clamps here. */
const MAX_FLOWERS = 96;
/**
 * Distinct flower silhouettes. Three, for the reason `GrowthField` documents:
 * per-instance scaling buys proportion variety, but only distinct geometry
 * buys *facet* variety, and a meadow of one bloom scaled forty ways reads as a
 * repeated prop the moment the camera moves. Here the variants differ in petal
 * count and in whether the ring of blades is phase-offset, which is enough.
 */
const VARIANTS = 3;

/**
 * The pose baked into the vertex buffer.
 *
 * Nothing reads these at run time — `PetalMaterial` rewrites every vertex from
 * live uniforms. They exist because three needs *a* position attribute to
 * compute a bounding sphere from and because the shadow depth material is
 * generated by three and is therefore **not** patched, so an unposed buffer
 * would cast the shadow of a flat star. Baking the closed bud means the worst
 * case is a bud-shaped shadow under an open flower, which is why this field
 * turns `castShadow` off and takes only the receive.
 */
const NOMINAL = {
  stemTop: 0.44,
  stemRadius: 0.05,
  heartRadius: 0.09,
  width: 0.3,
  widthBias: 0.78,
  taper: 0.7,
  budMidOut: 0.02,
  budMidUp: 0.34,
  budTipOut: 0.05,
  budTipUp: 0.7
};

/* Module-scope scratch. Nothing in the frame path allocates — invariant I3. */
const _emit = {};
const _pos = new Vector3();
const _dir = new Vector3();
const _centre = new Vector3();
const _hand = new Vector3();

/**
 * One flower, in `GrowthField`'s unit space: footprint inside a circle of
 * radius 0.5 on `y = 0`, tip at `y = 1`.
 *
 * A tapered stalk prism with a cap, and a ring of `petals` blades hinged on the
 * rim of the cap. Every vertex carries `aPetal = (along, across, bearing,
 * blade dice)` and `aPart` (0 stalk, 1 petal) — those four numbers plus the two
 * `GrowthField` attributes are the entire input to the pose, which is built in
 * the vertex shader. See `materials/PetalMaterial.js`.
 *
 * A blade is three columns wide (`across` = -1, 0, +1) rather than two,
 * because the middle column is the **midrib**: the lengthwise crease is a tent
 * fold about it, and a two-column blade has nothing to fold about. That is the
 * single reason the tessellation is not the obvious quad strip.
 */
function createFlowerGeometry(variant, shape) {
  const blades = Math.max(
    3,
    Math.min(14, Math.round(shape.petals) + (variant === 1 ? 1 : variant === 2 ? -1 : 0))
  );
  const segments = Math.max(2, Math.min(24, Math.round(shape.segments)));
  const sides = Math.max(3, Math.min(16, Math.round(shape.sides)));

  const stalkVerts = sides * 2 + 1;
  const total = stalkVerts + blades * (segments + 1) * 3;
  const triangles = sides * 3 + blades * segments * 4;

  const position = new Float32Array(total * 3);
  const petal = new Float32Array(total * 4);
  const part = new Float32Array(total);
  const index = new Uint16Array(triangles * 3);

  let v = 0;
  let t = 0;

  /* --- the stalk: two rings and a cap fan --- */
  for (let ring = 0; ring < 2; ring++) {
    const along = ring;
    const r = NOMINAL.stemRadius + (NOMINAL.heartRadius - NOMINAL.stemRadius) * along;
    for (let s = 0; s < sides; s++) {
      const bearing = (s / sides) * TAU;
      position[v * 3] = Math.cos(bearing) * r;
      position[v * 3 + 1] = NOMINAL.stemTop * along;
      position[v * 3 + 2] = Math.sin(bearing) * r;
      // `across` doubles as a 0..1 radial scale on the stalk, which is how the
      // cap gets a centre vertex without a fourth attribute.
      petal[v * 4] = along;
      petal[v * 4 + 1] = 1;
      petal[v * 4 + 2] = bearing;
      petal[v * 4 + 3] = 0;
      part[v] = 0;
      v++;
    }
  }
  const capCentre = v;
  position[v * 3 + 1] = NOMINAL.stemTop;
  petal[v * 4] = 1;
  petal[v * 4 + 1] = 0;
  petal[v * 4 + 2] = 0;
  petal[v * 4 + 3] = 0;
  part[v] = 0;
  v++;

  // The index names below are deliberately not `a`/`b`/`c`/`d`: `c` is the
  // conventional alias for a settings block everywhere in this project, and
  // `scripts/check.mjs` drops every `c.<key>` read in a file that also binds
  // `c` to something that is not a settings block. Four characters of loop
  // variable is not worth losing the whole file's static cross-check over.
  for (let s = 0; s < sides; s++) {
    const n0 = s;
    const n1 = (s + 1) % sides;
    const n2 = sides + s;
    const n3 = sides + ((s + 1) % sides);
    index[t++] = n0;
    index[t++] = n2;
    index[t++] = n3;
    index[t++] = n0;
    index[t++] = n3;
    index[t++] = n1;
    index[t++] = n2;
    index[t++] = capCentre;
    index[t++] = n3;
  }

  /* --- the ring of blades --- */
  for (let k = 0; k < blades; k++) {
    // Variant 2 is offset half a slot so two flowers standing side by side do
    // not present their petals on the same bearings.
    const bearing = ((k + (variant === 2 ? 0.5 : 0)) / blades) * TAU;
    // A per-blade dice roll, deterministic in the geometry rather than random,
    // so the same variant always tessellates identically and `syncGeometry`'s
    // change test stays honest.
    const dice = hash11(k * 12.9898 + variant * 7.13 + blades * 3.77);
    const base = v;

    for (let j = 0; j <= segments; j++) {
      const along = j / segments;
      const ms = 1 - along;
      const cx =
        ms * ms * NOMINAL.heartRadius +
        2 * ms * along * NOMINAL.budMidOut +
        along * along * NOMINAL.budTipOut;
      const cy = 2 * ms * along * NOMINAL.budMidUp + along * along * NOMINAL.budTipUp;
      const halfWidth =
        NOMINAL.width *
        Math.pow(Math.max(Math.sin(Math.PI * Math.pow(along, NOMINAL.widthBias)), 0), NOMINAL.taper);

      for (let i = 0; i < 3; i++) {
        const across = i - 1;
        position[v * 3] = Math.cos(bearing) * cx - Math.sin(bearing) * (across * halfWidth);
        position[v * 3 + 1] = NOMINAL.stemTop + cy;
        position[v * 3 + 2] = Math.sin(bearing) * cx + Math.cos(bearing) * (across * halfWidth);
        petal[v * 4] = along;
        petal[v * 4 + 1] = across;
        petal[v * 4 + 2] = bearing;
        petal[v * 4 + 3] = dice;
        part[v] = 1;
        v++;
      }
    }

    for (let j = 0; j < segments; j++) {
      for (let i = 0; i < 2; i++) {
        const n0 = base + j * 3 + i;
        const n1 = n0 + 1;
        const n2 = n0 + 3;
        const n3 = n2 + 1;
        index[t++] = n0;
        index[t++] = n2;
        index[t++] = n1;
        index[t++] = n1;
        index[t++] = n2;
        index[t++] = n3;
      }
    }
  }

  const geometry = new BufferGeometry();
  geometry.setAttribute('position', new BufferAttribute(position, 3));
  geometry.setAttribute('aPetal', new BufferAttribute(petal, 4));
  geometry.setAttribute('aPart', new BufferAttribute(part, 1));
  geometry.setIndex(new BufferAttribute(index, 1));
  geometry.computeVertexNormals();
  return geometry;
}

/**
 * BLOOMBURST — the meadow that is forced open and then thrown away.
 *
 * Four beats over three phases:
 *
 *   1. **travel** — a growth front runs out across the floor to the circle the
 *      indicator drew, laying a mat of moss behind it.
 *   2. **grow & open** — the first part of the impact phase. Stalks push up out
 *      of the footprint each carrying a closed bud, and the buds **unfurl in a
 *      wave** that starts in the middle of the circle and runs out to the
 *      boundary. The flowers in the centre are fully open before the ones on
 *      the rim have cleared the ground.
 *   3. **hold** — the field stands open, breathing pollen off its hearts.
 *   4. **release** — the fade phase. Every petal in the circle lets go on the
 *      *same frame*, tumbling outward, and the pollen they were carrying swells
 *      into a raymarched volume that drifts and settles while the bare stalks
 *      fold back into the floor behind it.
 *
 * **The trick is the unfurl, and none of it is on the CPU.** Each petal is
 * stored once, unbent, as `(along, across, bearing, dice)`; the vertex shader
 * poses it from a quadratic Bezier whose two free control points lerp from a
 * bud pose to an open pose. The lerp parameter is `1 - aBirth` — the
 * per-instance value `GrowthField` already writes and already re-derives from
 * its live `birthFade`, which this ability feeds `unfurlTime`. So the wave, the
 * opening and the shape of the opening are three separate live controls over a
 * field that is already standing, and `unfurlCurve` — the exponent on that
 * lerp — is the one that carries the character of the whole cast.
 *
 * The first version tried to bake the bend into the geometry and let the field
 * scale it. That cannot work and it is worth writing down why: `GrowthField`
 * shares **one** geometry per variant across every instance of it, and the bend
 * is a function of time *per instance*. Baking it gives the entire meadow a
 * single pose, which is a photograph of a flower bed, not a bloom.
 *
 * **The rule that makes the editor work.** A flower record holds nothing but
 * dice and one timestamp — `GrowthField` owns them and this class never adds
 * to them. Not one metre, radian or second is captured: the seat of the ring,
 * the height of a stalk, the pose of a petal, the size of the pollen hull and
 * the death of the last mote are all resolved against `settings.bloomburst`
 * inside the update loop, which runs on a zero-length frame too.
 */
export class BloomburstAbility extends Ability {
  constructor(context) {
    super('bloomburst', context);
  }

  /* ------------------------------------------------------------------ */
  /* Construction                                                        */
  /* ------------------------------------------------------------------ */

  createShaders() {
    const c = settings.bloomburst;

    this.material = createPetalMaterial(this.ctx.environment);

    /** Live params, allocated once. Refilled from settings every frame — I1. */
    this.growth = growthParams();
    this.growth.layout = GrowthLayout.ZONE;
    this.growth.emerge = GrowthEmerge.PUSH;
    this.growth.centre = new Vector3();
    /** The three numbers that cannot be a uniform, so they rebuild the mesh. */
    this.shape = { petals: c.petals, segments: c.petalSegments, sides: c.stalkSides };

    this.field = new GrowthField(this.group, {
      geometry: createFlowerGeometry,
      material: this.material,
      shape: this.shape,
      variants: VARIANTS,
      capacity: MAX_FLOWERS,
      layer: LAYER.WORLD,
      renderOrder: 2,
      // See NOMINAL: the depth material three generates for the shadow pass is
      // not patched, so it would cast the *bud* pose of an open flower. A wrong
      // shadow is louder than no shadow.
      castShadow: false,
      receiveShadow: true
    });
    // Assigned once, at construction. A closure built inside the update loop is
    // an allocation per instance per frame, which is exactly what I3 forbids.
    this.field.onBreach = (index, position, radius, height) =>
      this._breachFx(index, position, radius, height);

    /**
     * The pollen. A SPORE cylinder standing over the circle — barely there
     * while the flowers merely hold, and the entire read for the second after
     * they let go.
     *
     * CYLINDER rather than DOME because the pollen belongs to the *footprint*:
     * a dome puts its mass over the middle and tapers to nothing at the
     * boundary, which reads as a puff sitting on a meadow rather than as the
     * meadow itself having gone to dust.
     */
    this.pollen = new VolumeHull({
      hull: HullShape.CYLINDER,
      medium: Medium.SPORE,
      prefix: 'pollen',
      maxSteps: 40,
      renderOrder: 12
    });
    this.group.add(this.pollen.mesh);

    /** Re-rolled per cast so no two meadows draw the same ring. */
    this._seed = 0;
    /** Seconds since the field took hold. Drives the opening wave, nothing else. */
    this._bloomTime = 0;
    /** One-shot latch for the release, which is a single event across the field. */
    this._released = false;
  }

  createParticles() {
    const particles = this.ctx.particles;

    // Pollen: the signature system. Slow, additive, curl-driven — it has to
    // hang in the air rather than fly, because the flowers are giving it up,
    // not throwing it.
    this.pollenMotes = particles.get('bloomburst.pollen', {
      capacity: 2600,
      shape: ParticleShape.SOFT,
      additive: true,
      curl: true,
      softFade: 0.45
    });
    this.pollenMotes.uniforms.uDrag.value = 1.9;
    this.pollenMotes.uniforms.uEndSize.value = 0.5;
    this.pollenMotes.uniforms.uSizeIn.value = 0.1;
    this.pollenMotes.uniforms.uFadeIn.value = 0.12;
    this.pollenMotes.uniforms.uFadeOut.value = 0.45;

    // Torn petal fragments. LEAF, lit and non-additive: they are the only
    // opaque thing in the release and they are what makes it read as *matter*
    // being shed rather than as a light effect.
    this.confetti = particles.get('bloomburst.confetti', {
      capacity: 1600,
      shape: ParticleShape.LEAF,
      additive: false,
      lit: true,
      softFade: 0.3
    });
    this.confetti.uniforms.uDrag.value = 1.15;
    this.confetti.uniforms.uEndSize.value = 0.9;
    this.confetti.uniforms.uFadeIn.value = 0.05;
    this.confetti.uniforms.uFadeOut.value = 0.55;

    // A low green haze off the ground the field is growing out of.
    this.haze = particles.get('bloomburst.haze', {
      capacity: 1400,
      shape: ParticleShape.SMOKE,
      additive: false,
      curl: true,
      softFade: 1.0
    });
    this.haze.uniforms.uDrag.value = 2.2;
    this.haze.uniforms.uEndSize.value = 2.6;
    this.haze.uniforms.uSizeIn.value = 0.14;
    this.haze.uniforms.uFadeIn.value = 0.2;
    this.haze.uniforms.uFadeOut.value = 0.32;

    this.pollenEmitter = new RateEmitter();
    this.hazeEmitter = new RateEmitter();
  }

  /* ------------------------------------------------------------------ */
  /* Timing                                                              */
  /* ------------------------------------------------------------------ */

  get instanceCount() {
    return this.field.count;
  }

  /** Grow, open on the wave, then stand. */
  get impactDuration() {
    const c = settings.bloomburst;
    return Math.max(
      0.2,
      (c.riseTime + c.waveTime + c.unfurlTime + c.holdTime) * settings.global.lifetime
    );
  }

  /** The petals let go, then the stalks fold back in behind them. */
  get fadeDuration() {
    const c = settings.bloomburst;
    return Math.max(0.2, c.releaseTime + c.witherTime);
  }

  /** The live footprint, metres. What the indicator measured out. */
  get radius() {
    return Math.max(0.05, settings.bloomburst.zoneRadius);
  }

  /* ------------------------------------------------------------------ */
  /* Geometry — every metre resolved from live settings                   */
  /* ------------------------------------------------------------------ */

  /** The middle of the circle — the far end of the aimed line. */
  _centrePoint(out) {
    return this.pointAt(1, out).setY(0);
  }

  /** Where the cast leaves the caster, in world space. */
  _handPoint(out) {
    const c = settings.bloomburst;
    out
      .copy(this.origin)
      .addScaledVector(this.direction, c.handForward)
      .addScaledVector(this.side, c.handSide);
    out.y = c.handHeight;
    return out;
  }

  /**
   * How far the opening wave has crossed the circle, 0..1.
   *
   * A pure function of `_bloomTime` against the live `waveTime`, so the wave
   * re-times itself if the slider moves mid-cast.
   */
  _waveFront() {
    const c = settings.bloomburst;
    return Easing.outCubic(saturate(this._bloomTime / Math.max(0.02, c.waveTime)));
  }

  /** 0..1 — how far the petals have let go. Only ever non-zero in the fade. */
  _releaseAmount() {
    if (this.phase !== AbilityPhase.FADE) return 0;
    const c = settings.bloomburst;
    return Easing.outCubic(saturate(this.fadeTime / Math.max(0.02, c.releaseTime)));
  }

  /** 0..1 — how far the bare stalks have folded back into the floor. */
  _witherAmount() {
    if (this.phase !== AbilityPhase.FADE) return 0;
    const c = settings.bloomburst;
    return saturate((this.fadeTime - c.releaseTime) / Math.max(0.05, c.witherTime));
  }

  /**
   * Refill the growth params from live settings.
   *
   * Every number here is re-read on every call, including on a zero-length
   * frame. Nothing is cached between frames and nothing is captured at spawn —
   * that is the whole of I1 for this ability.
   */
  _fillGrowth() {
    const c = settings.bloomburst;
    const g = settings.global;
    const p = this.growth;
    const R = this.radius;

    this._centrePoint(p.centre);
    p.origin = this.origin;
    p.direction = this.direction;
    p.side = this.side;
    p.length = this.length;

    p.radius = R;
    p.innerRadius = R * saturate(c.innerFrac);
    p.radialCurve = c.radialCurve;
    p.radialJitter = c.radialJitter;
    p.angleJitter = c.angleJitter;

    p.heightNear = c.heightNear;
    p.height = c.height;
    p.heightCurve = c.heightCurve;
    p.heightJitter = c.heightJitter;
    p.radiusNear = c.stalkRadius;
    p.radius2 = c.stalkRadiusTop;
    p.radiusCurve = c.radiusCurve;
    p.radiusJitter = c.radiusJitter;

    p.lean = c.lean;
    p.leanJitter = c.leanJitter;
    p.leanRamp = c.leanRamp;
    // Both, and both non-zero: GrowthField normalises the blend of them, so a
    // single non-zero weight would be scaled away and its slider would be dead.
    p.leanOutward = c.leanOutward;
    p.leanForward = c.leanForward;
    p.tilt = c.tilt;
    p.twist = c.twist;

    p.riseTime = c.riseTime;
    p.riseOvershoot = c.riseOvershoot;
    p.settle = c.settle;
    p.springRate = c.springRate;
    p.emergeSink = c.emergeSink;
    p.birthScale = c.birthScale;
    p.breachAt = c.breachAt;
    p.sinkDepth = c.sinkDepth;
    // The coupling that makes the whole ability work: GrowthField's birth flash
    // *is* Bloomburst's unfurl clock. It has to span the rise as well as the
    // opening, because the ramp starts the instant the stalk is triggered and
    // the bud is not allowed to split until the stalk is up — `PetalMaterial`
    // splits it at `uOpenDelay`, which is derived from the same two numbers.
    p.birthFade = Math.max(0.02, c.riseTime + c.unfurlTime);

    p.randomness = g.randomness;
  }

  /* ------------------------------------------------------------------ */
  /* Casting                                                             */
  /* ------------------------------------------------------------------ */

  onSpawn() {
    const c = settings.bloomburst;

    this.pollenEmitter.reset();
    this.hazeEmitter.reset();
    this._bloomTime = 0;
    this._released = false;

    // The one thing a cast captures, besides the field's own dice and the
    // timestamps it hands each flower.
    this._seed = Math.random() * 100;

    this.field.plant(Math.min(MAX_FLOWERS, Math.round(c.flowers)), c.coreShare);
    this.pollen.setFade(0);

    this._sync(0, 0);
    this._muzzleFx();
  }

  /* ------------------------------------------------------------------ */
  /* Feedback                                                            */
  /* ------------------------------------------------------------------ */

  /**
   * Push the live settings into the petal material, the pollen hull and the
   * three particle systems, and rebuild every flower matrix.
   *
   * @param {number} release 0..1 — how far the petals have let go
   * @param {number} wither  0..1 — how far the bare stalks have folded back
   */
  _sync(release, wither) {
    const c = settings.bloomburst;
    const g = settings.global;

    /* --- the flowers --- */
    this.shape.petals = c.petals;
    this.shape.segments = c.petalSegments;
    this.shape.sides = c.stalkSides;
    this.field.syncGeometry(this.shape);

    this.material.userData.sync(release);
    this._fillGrowth();
    this.field.update(this.age, this.growth, wither);

    /* --- the pollen volume --- */
    // Its footprint is the circle's, swelling as the petals are given up; its
    // base sinks as it settles. Both re-resolved here, never captured.
    const R = this.radius * c.pollenRadius * (1 + (c.pollenSwell - 1) * release);
    const lift = Math.max(0.05, c.pollenLift * (1 - c.pollenSettle * wither));
    const idle = saturate(c.pollenHaze);
    const fade = Math.max(idle * (1 - wither), release * (1 - wither));

    this._centrePoint(_pos);
    _pos.y = c.pollenBase * (1 - c.pollenSettle * wither);
    this.pollen.place(_pos, this.direction).setSize(R, lift, R).setFade(fade).sync(c, g);

    /* --- the three particle systems --- */
    this.pollenMotes.setGradient(
      getColor(c.colorPollenA),
      getColor(c.colorPollenB),
      getColor(c.colorPollenC),
      getColor(c.colorPollenD)
    );
    this.pollenMotes.uniforms.uGravity.value.set(0, c.pollenDrift, 0);
    this.pollenMotes.uniforms.uSizeScale.value = c.pollenSize * g.particleSize * 7;
    this.pollenMotes.uniforms.uLifeScale.value = c.pollenLifetime * 0.5 * g.particleLifetime;
    this.pollenMotes.uniforms.uSpeedScale.value = g.particleSpeed;
    this.pollenMotes.uniforms.uOpacity.value = g.opacity;
    this.pollenMotes.uniforms.uGlow.value = c.pollenGlow * g.glow;
    this.pollenMotes.uniforms.uTurbulence.value = c.pollenTurbulence * g.turbulence;

    this.confetti.setGradient(
      getColor(c.colorConfettiA),
      getColor(c.colorConfettiB),
      getColor(c.colorConfettiC),
      getColor(c.colorConfettiD)
    );
    this.confetti.uniforms.uGravity.value.set(0, c.confettiGravity, 0);
    this.confetti.uniforms.uSizeScale.value = c.confettiSize * g.particleSize * 7;
    this.confetti.uniforms.uLifeScale.value = c.confettiLifetime * 0.5 * g.particleLifetime;
    this.confetti.uniforms.uSpeedScale.value = g.particleSpeed;
    this.confetti.uniforms.uOpacity.value = g.opacity;

    this.haze.setGradient(
      getColor(c.colorHazeA),
      getColor(c.colorHazeB),
      getColor(c.colorHazeC),
      getColor(c.colorHazeD)
    );
    this.haze.uniforms.uGravity.value.set(0, c.hazeRise, 0);
    this.haze.uniforms.uSizeScale.value = c.hazeSize * g.particleSize;
    this.haze.uniforms.uLifeScale.value = c.hazeLifetime * 0.5 * g.particleLifetime;
    this.haze.uniforms.uSpeedScale.value = c.hazeSpeed * g.particleSpeed;
    this.haze.uniforms.uOpacity.value = c.hazeOpacity * g.opacity;
    this.haze.uniforms.uTurbulence.value = 0.4 * g.turbulence;
  }

  /** The puff of spores at the caster's hand as the growth front leaves it. */
  _muzzleFx() {
    const c = settings.bloomburst;
    const g = settings.global;

    this._handPoint(_hand);

    this.ctx.bursts.spawn(BurstMode.EARTH, _hand, {
      radius: c.muzzleSize * 0.25,
      endRadius: c.muzzleSize * g.explosionIntensity,
      life: 0.45,
      intensity: c.muzzleIntensity,
      opacity: 0.6,
      fresnel: 1.3,
      displace: 0.55,
      colorA: getColor(c.colorBurstA),
      colorB: getColor(c.colorBurstB),
      colorC: getColor(c.colorBurstC)
    });

    _emit.position = _hand;
    _emit.radius = 0.16;
    _emit.direction = _dir.copy(this.direction).multiplyScalar(0.6).setY(0.5).normalize();
    _emit.speed = c.pollenSpeed * 3;
    _emit.speedVariance = 0.8;
    _emit.spread = 0.9;
    _emit.inherit = null;
    _emit.anchor = null;
    _emit.size = 0.09;
    _emit.sizeVariance = 0.7;
    _emit.life = c.pollenLifetime * 0.6;
    _emit.lifeVariance = 0.5;
    _emit.spin = 0;
    _emit.tint = null;
    _emit.time = frame.uTime.value;
    this.pollenMotes.emit(Math.round(28 * g.particleCount), _emit);

    this.ctx.flash.trigger(getColor(c.colorCastFlash), c.castFlash * g.explosionIntensity);
    this.lightBoost = c.lightIntensity * 0.5 * g.explosionIntensity;
  }

  /** Moss and haze laid under the growth front while it races out. */
  _frontFx(dt) {
    const c = settings.bloomburst;
    const g = settings.global;

    const hazeCount = Math.round(this.hazeEmitter.tick(dt, c.hazeRate * 0.55) * g.particleCount);
    if (hazeCount > 0) {
      _emit.position = _pos.copy(this.position).setY(0.1);
      _emit.radius = 0.55;
      _emit.direction = _dir.set(0, 1, 0);
      _emit.speed = c.hazeSpeed;
      _emit.speedVariance = 0.7;
      _emit.spread = 1.0;
      _emit.inherit = null;
      _emit.anchor = null;
      _emit.size = 0.7;
      _emit.sizeVariance = 0.5;
      _emit.life = c.hazeLifetime * 0.8;
      _emit.lifeVariance = 0.4;
      _emit.spin = 0.4;
      _emit.tint = null;
      _emit.time = frame.uTime.value;
      this.haze.emit(hazeCount, _emit);
    }
  }

  /**
   * A puff of spores and a mat of moss where a stalk breaks the surface.
   *
   * `GrowthField` hands us the index, the live world position and the live
   * radius and height, so nothing here has to re-derive a metre the field has
   * already resolved.
   */
  _breachFx(index, position, radius, height) {
    const c = settings.bloomburst;
    const g = settings.global;

    _emit.position = _pos.copy(position).setY(0.05);
    _emit.radius = radius * 0.8;
    _emit.direction = _dir.set(0, 1, 0);
    _emit.speed = c.hazeSpeed * 1.4;
    _emit.speedVariance = 0.7;
    _emit.spread = 1.0;
    _emit.inherit = null;
    _emit.anchor = null;
    _emit.size = 0.45;
    _emit.sizeVariance = 0.5;
    _emit.life = c.hazeLifetime * 0.6;
    _emit.lifeVariance = 0.4;
    _emit.spin = 0.5;
    _emit.tint = null;
    _emit.time = frame.uTime.value;
    this.haze.emit(Math.round(2 * g.particleCount), _emit);

    // Only some stalks get a mat. Thirty-eight overlapping decals is a green
    // disc, and the point of the mat is that the ground is *patchy* under a
    // meadow that grew in half a second.
    if (hash11(index * 3.7 + this._seed) < 0.45) {
      this.ctx.decals.spawn(DecalType.FOAM, position, {
        radius: c.mossRadius * randRange(0.6, 1.25),
        life: c.mossLife,
        intensity: c.mossIntensity,
        colorA: getColor(c.colorMoss),
        colorB: getColor(c.colorMossEdge)
      });
    }
  }

  /**
   * Pollen off the open hearts, and haze off the ground between them.
   *
   * The pollen is emitted at a *flower*, not at a random point in the circle:
   * `positionOf`/`heightOf` read the live placement straight back out of the
   * field, so a mote leaves the head of a bloom that is actually there and
   * moves with it when `zoneRadius` is dragged.
   *
   * @param {number} scale 0..1 — thinned out as the field dies
   */
  _fieldFx(dt, scale) {
    const c = settings.bloomburst;
    const g = settings.global;
    const time = frame.uTime.value;
    const count = this.field.count;
    if (count <= 0) return;

    const pollenCount = Math.round(this.pollenEmitter.tick(dt, c.pollenRate * scale) * g.particleCount);
    if (pollenCount > 0) {
      const index = Math.min(count - 1, (Math.random() * count) | 0);
      const open = this.field.emergenceOf(index, this.age, this.growth);
      if (open > 0.2) {
        this.field.positionOf(index, this.growth, _pos);
        _pos.y += this.field.heightOf(index, this.growth) * c.stemFrac;
        _emit.position = _pos;
        _emit.radius = this.field.radiusOf(index, this.growth) * c.petalWidth * 2;
        _emit.direction = _dir.set(0, 1, 0);
        _emit.speed = c.pollenSpeed;
        _emit.speedVariance = 0.85;
        _emit.spread = 1.0;
        _emit.inherit = null;
        _emit.anchor = null;
        _emit.size = 0.07;
        _emit.sizeVariance = 0.7;
        _emit.life = c.pollenLifetime;
        _emit.lifeVariance = 0.5;
        _emit.spin = 0;
        _emit.tint = null;
        _emit.time = time;
        this.pollenMotes.emit(pollenCount, _emit);
      }
    }

    const hazeCount = Math.round(this.hazeEmitter.tick(dt, c.hazeRate * scale) * g.particleCount);
    if (hazeCount > 0) {
      const bearing = Math.random() * TAU;
      const r = this.radius * Math.sqrt(Math.random());
      this._centrePoint(_centre);
      _pos.set(_centre.x + Math.cos(bearing) * r, 0.12, _centre.z + Math.sin(bearing) * r);
      _emit.position = _pos;
      _emit.radius = this.radius * 0.15;
      _emit.direction = _dir.set(0, 1, 0);
      _emit.speed = c.hazeSpeed;
      _emit.speedVariance = 0.7;
      _emit.spread = 0.95;
      _emit.inherit = null;
      _emit.anchor = null;
      _emit.size = 0.8;
      _emit.sizeVariance = 0.5;
      _emit.life = c.hazeLifetime;
      _emit.lifeVariance = 0.4;
      _emit.spin = 0.35;
      _emit.tint = null;
      _emit.time = time;
      this.haze.emit(hazeCount, _emit);
    }
  }

  /** The one-shot when every petal in the circle lets go at once. */
  _releaseFx() {
    const c = settings.bloomburst;
    const g = settings.global;
    const time = frame.uTime.value;
    const R = this.radius;

    this._centrePoint(_centre);
    _pos.copy(_centre).setY(c.heightNear * 0.5);

    this.ctx.bursts.spawn(BurstMode.AIR, _pos, {
      radius: c.burstSize * 0.3,
      endRadius: c.burstSize * g.explosionIntensity,
      life: 0.9,
      intensity: c.burstIntensity,
      opacity: 0.45,
      fresnel: 1.5,
      displace: 0.5,
      squash: 0.55,
      colorA: getColor(c.colorBurstA),
      colorB: getColor(c.colorBurstB),
      colorC: getColor(c.colorBurstC)
    });

    /* the pollen the field was holding, all of it at once */
    _emit.position = _pos;
    _emit.radius = R * 0.85;
    _emit.direction = _dir.set(0, 1, 0);
    _emit.speed = c.pollenSpeed * 2.4;
    _emit.speedVariance = 0.9;
    _emit.spread = 1.0;
    _emit.inherit = null;
    _emit.anchor = null;
    _emit.size = 0.08;
    _emit.sizeVariance = 0.8;
    _emit.life = c.pollenLifetime * 1.4;
    _emit.lifeVariance = 0.55;
    _emit.spin = 0;
    _emit.tint = null;
    _emit.time = time;
    this.pollenMotes.emit(Math.round(c.burstPollen * g.particleCount), _emit);

    /* and the petals themselves */
    _emit.radius = R * 0.9;
    _emit.direction = _dir.set(0, 0.55, 0).normalize();
    _emit.speed = c.confettiSpeed;
    _emit.speedVariance = 0.9;
    _emit.spread = 1.0;
    _emit.size = 0.12;
    _emit.sizeVariance = 0.7;
    _emit.life = c.confettiLifetime;
    _emit.lifeVariance = 0.5;
    _emit.spin = c.confettiSpin;
    this.confetti.emit(Math.round(c.burstConfetti * g.particleCount), _emit);

    this.ctx.decals.spawn(DecalType.DUSTRING, _centre, {
      radius: c.shockRadius * g.explosionIntensity,
      life: 0.9,
      width: 0.06,
      intensity: 0.7,
      colorA: getColor(c.colorShockA),
      colorB: getColor(c.colorShockB)
    });

    this.ctx.shake.add(
      c.impactShake * g.explosionIntensity * g.cameraShake,
      1 / Math.max(0.1, c.shakeDuration),
      16
    );
    this.ctx.flash.trigger(getColor(c.colorFlash), c.impactFlash * g.explosionIntensity);
    this.lightBoost = c.lightIntensity * 1.2 * g.explosionIntensity;
  }

  /* ------------------------------------------------------------------ */
  /* Phases                                                              */
  /* ------------------------------------------------------------------ */

  onTravel(dt) {
    this._sync(0, 0);

    // The light rides the front, just off the floor.
    this.position.y = 0.3;

    this._frontFx(dt);
    this.ctx.shake.rumble(settings.bloomburst.rumble * settings.global.cameraShake, dt);
  }

  onImpact() {
    const c = settings.bloomburst;
    const g = settings.global;

    this._bloomTime = 0;
    this._centrePoint(_centre);

    /* the mat of moss the whole field is seated on */
    this.ctx.decals.spawn(DecalType.FOAM, _centre, {
      radius: this.radius * c.mossSpread,
      life: c.mossLife * 1.5,
      intensity: c.mossIntensity * 0.8,
      colorA: getColor(c.colorMoss),
      colorB: getColor(c.colorMossEdge)
    });

    /* and the ring pushed out as it takes hold */
    this.ctx.decals.spawn(DecalType.DUSTRING, _centre, {
      radius: c.shockRadius * 0.8 * g.explosionIntensity,
      life: 0.8,
      width: 0.05,
      intensity: 0.6,
      colorA: getColor(c.colorShockA),
      colorB: getColor(c.colorShockB)
    });

    this.ctx.shake.add(
      c.impactShake * 0.5 * g.explosionIntensity * g.cameraShake,
      1 / Math.max(0.1, c.shakeDuration),
      14
    );
    this.lightBoost = c.lightIntensity * 0.7 * g.explosionIntensity;
  }

  onFade(dt, t) {
    const c = settings.bloomburst;

    if (t <= 1) this._bloomTime += dt;

    // The wave. `triggerRadial` fills from the middle outward; `waveInvert`
    // runs it the other way, in which case the core group has to be held until
    // the front has actually reached the middle or it would open first and
    // give the reversal away.
    const invert = !!c.waveInvert;
    const front = t <= 1 ? this._waveFront() : 1;
    this.field.triggerRadial(
      this.age,
      front,
      c.waveStagger,
      invert,
      !invert || front >= 0.999
    );

    const release = this._releaseAmount();
    const wither = this._witherAmount();

    if (!this._released && release > 0) {
      this._released = true;
      this._releaseFx();
    }

    this._sync(release, wither);

    // The light climbs into the field and stays there.
    this._centrePoint(this.position);
    this.position.y = c.heightNear * saturate(c.lightHeight) * (1 - wither);

    this._fieldFx(dt, t <= 1 ? 1 : (1 - release) * 0.5);
  }

  onDestroy() {
    this.field.clear();
    this.pollen.setFade(0);
    this.material.userData.sync(0);
    this._released = false;
    this._bloomTime = 0;
  }

  dispose() {
    this.field.dispose();
    this.material.dispose();
    this.pollen.dispose();
    super.dispose();
  }
}
